/**
  * @file    oled.c
  * @brief   Text-only driver for a 128x64 SSD1315/SSD1306 OLED on STM32F042 (HAL, I2C).
  */
#include "oled.h"
#include <stdarg.h>
#include <stdio.h>

#define CTRL_CMD    0x00U   /* I2C control byte: following bytes are commands   */
#define CTRL_DATA   0x40U   /* I2C control byte: following bytes are display RAM */
#define CELL_W      6U      /* 5 px glyph + 1 px gap */
#define FONT_FIRST  32
#define FONT_LAST   126

/* ==========================================================================
 * Bus layer. Everything hardware specific is in this block.
 * ========================================================================== */
#if !OLED_PORT_CUSTOM

#include "custom_bus.h"   /* hi2c1, shared with the VL53L4CD driver; init via BSP_I2C1_Init() */

void OLED_PortDelayMs(uint32_t ms)
{
  HAL_Delay(ms);
}

int32_t OLED_PortWrite(uint8_t ctrl, const uint8_t *data, uint16_t len)
{
  /* The control byte goes in the "memory address" slot, so this sends exactly
     START, addr+W, ctrl, data[0..len-1], STOP. HAL handles NACK, stale TXDR and timeouts. */
  if (HAL_I2C_Mem_Write(&OLED_I2C_HANDLE, (uint16_t)(OLED_I2C_ADDR << 1), ctrl,
                        I2C_MEMADD_SIZE_8BIT, (uint8_t *)data, len,
                        OLED_I2C_TIMEOUT_MS) != HAL_OK)
  {
    return -1;
  }
  return 0;
}

#endif /* !OLED_PORT_CUSTOM */

